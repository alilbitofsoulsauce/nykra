"""Consent-based, reversible, per-user Windows developer installation.

No administrator permissions, no app injection, no changes to Rel.AI binaries,
and no network listener. Copies Nykra's Python standard-library package into
the user's application directory; a truly standalone executable is future work.
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

from . import __version__
from .store import NykraError, default_home
from .workstation import assert_not_running, read_health, request_stop

INSTALL_MARKER = "nykra-windows-user-install-v1"
AUTOSTART_MARKER = "REM NYKRA-MANAGED-AUTOSTART-V1"
AUTOSTART_FILENAME = "Nykra.cmd"
LAUNCHER_SOURCE = '''"""Nykra per-user installed runtime, generated by the Nykra installer."""
import sys
from pathlib import Path
root = Path(__file__).resolve().parent
sys.path.insert(0, str(root))
from nykra.__main__ import main
raise SystemExit(main(["--home", str(root.parent), "daemon"]))
'''


def startup_folder() -> Path:
    appdata = os.environ.get("APPDATA")
    if not appdata:
        raise NykraError("APPDATA environment variable is unavailable")
    return Path(appdata) / "Microsoft" / "Windows" / "Start Menu" / "Programs" / "Startup"


def _installation_paths(home: Path | str | None = None, startup: Path | str | None = None) -> tuple[Path, Path]:
    root = Path(home).expanduser().resolve() if home is not None else default_home()
    start_dir = Path(startup).expanduser().resolve() if startup is not None else startup_folder()
    return root, start_dir / AUTOSTART_FILENAME


def _managed_startup_content(pyexe: Path, launcher: Path) -> str:
    # cmd.exe substitutes %VARIABLES%; reject characters that could change arguments.
    unsafe = '"\r\n%&|<>^!'
    for path in (pyexe, launcher):
        if any(c in str(path) for c in unsafe):
            raise NykraError("Installer path contains an unsupported Windows CMD character")
    return f"@echo off\r\n{AUTOSTART_MARKER}\r\nstart \"\" \"{pyexe}\" \"{launcher}\"\r\n"


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _atomic(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp = tempfile.mkstemp(prefix=".nykra-", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as out:
            out.write(data)
            out.flush()
            os.fsync(out.fileno())
        os.replace(temp, path)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


def _read_manifest(home: Path) -> dict | None:
    path = home / "installation.json"
    if not path.exists():
        return None
    try:
        obj = json.loads(path.read_text(encoding="utf-8"))
    except (ValueError, OSError) as exc:
        raise NykraError("Existing Nykra installation manifest is unreadable") from exc
    if not isinstance(obj, dict) or obj.get("marker") != INSTALL_MARKER:
        raise NykraError("Unrecognized installation manifest; refusing overwrite")
    return obj


def installed_status(home: Path | str | None = None, startup: Path | str | None = None) -> dict:
    root, autostart = _installation_paths(home, startup)
    manifest = _read_manifest(root)
    owned = bool(manifest and manifest.get("startup_path") == str(autostart))
    match = False
    if owned and autostart.is_file():
        match = _sha(autostart.read_bytes()) == manifest.get("startup_sha256")
    return {
        "installed": bool(manifest),
        "version": manifest.get("version") if manifest else None,
        "autostart_registered": match,
        "autostart_owned": owned,
        "runtime_ready": bool(manifest and (root / "runtime" / "run.py").is_file()
                              and (root / "runtime" / "nykra" / "workstation.py").is_file()),
        "runtime": read_health(root),
    }


def _pythonw() -> Path:
    exe = Path(sys.executable).resolve()
    if sys.platform == "win32":
        with_windowless = exe.with_name("pythonw.exe")
        if with_windowless.is_file():
            return with_windowless
    return exe


def start_installed(home: Path | str | None = None, *, startup: Path | str | None = None,
                    wait_seconds: float = 5.0) -> dict:
    root, _ = _installation_paths(home, startup)
    manifest = _read_manifest(root)
    if manifest is None:
        raise NykraError("Nykra must be installed before starting the background runtime")
    current = read_health(root)
    if current.get("healthy"):
        return {"started": True, "already_running": True, "runtime": current}
    executable = Path(manifest.get("python_executable", ""))
    runner = root / "runtime" / "run.py"
    if not executable.is_file() or not runner.is_file():
        raise NykraError("Installed Python runtime or Nykra launcher is missing; run install again")
    flags = subprocess.CREATE_NO_WINDOW | subprocess.DETACHED_PROCESS if sys.platform == "win32" else 0
    subprocess.Popen([str(executable), str(runner)],
                     cwd=str(runner.parent),
                     stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                     stderr=subprocess.DEVNULL, creationflags=flags,
                     close_fds=True)
    deadline = time.monotonic() + max(0.1, wait_seconds)
    while time.monotonic() < deadline:
        current = read_health(root)
        if current.get("healthy"):
            return {"started": True, "already_running": False, "runtime": current}
        time.sleep(0.1)
    return {"started": False, "reason": "runtime_not_ready", "runtime": read_health(root)}


def install_user(home: Path | str | None = None, *, startup: Path | str | None = None,
                 source: Path | str | None = None, activate: bool = False) -> dict:
    """User-profile installation. Activation is explicit to avoid persistent surprise."""
    if sys.platform != "win32" and startup is None:
        raise NykraError("Per-user autostart is currently supported only on Windows")
    root, autostart = _installation_paths(home, startup)
    existing = _read_manifest(root)
    if existing:
        status = installed_status(root, autostart.parent)
        if not status["autostart_registered"] and autostart.exists():
            raise NykraError("Nykra autostart file was changed; refusing overwrite")
        if status["runtime"].get("healthy"):
            stopped = request_stop(root)
            if not stopped["stopped"]:
                raise NykraError("Nykra background runtime could not be stopped safely for an update")
        assert_not_running(root)
    elif autostart.exists():
        raise NykraError("An unmanaged startup entry named Nykra.cmd already exists")

    package = Path(source).expanduser().resolve() if source else Path(__file__).resolve().parent
    if not (package / "__init__.py").is_file() or not (package / "workstation.py").is_file():
        raise NykraError("Missing Nykra package sources")
    root.mkdir(parents=True, exist_ok=True)
    runtime = root / "runtime"
    stage = Path(tempfile.mkdtemp(prefix=".nykra-stage-", dir=root))
    old = root / ".nykra-runtime-previous"
    if old.exists():
        raise NykraError("Previous installer transaction needs manual review before update")
    try:
        shutil.copytree(package, stage / "nykra", ignore=shutil.ignore_patterns("__pycache__", "*.pyc"), dirs_exist_ok=True)
        (stage / "run.py").write_text(LAUNCHER_SOURCE, encoding="utf-8")
        pyexe = _pythonw()
        startup_data = _managed_startup_content(pyexe, runtime / "run.py").encode("utf-8")
        if runtime.exists():
            runtime.rename(old)
        try:
            stage.rename(runtime)
            _atomic(autostart, startup_data)
            manifest = {
                "marker": INSTALL_MARKER, "version": __version__,
                "python_executable": str(pyexe),
                "startup_path": str(autostart),
                "startup_sha256": _sha(startup_data),
            }
            _atomic(root / "installation.json", (json.dumps(manifest, indent=2) + "\n").encode("utf-8"))
        except Exception:
            if runtime.exists():
                shutil.rmtree(runtime)
            if old.exists():
                old.rename(runtime)
            raise
        if old.exists():
            shutil.rmtree(old)
    finally:
        if stage.exists():
            shutil.rmtree(stage)
    result = installed_status(root, autostart.parent)
    if activate:
        result["activation"] = start_installed(root, startup=autostart.parent)
    return result


def uninstall_user(home: Path | str | None = None, *, startup: Path | str | None = None) -> dict:
    root, autostart = _installation_paths(home, startup)
    manifest = _read_manifest(root)
    if not manifest:
        return {"uninstalled": True, "already_absent": True}
    status = installed_status(root, autostart.parent)
    if not status["autostart_owned"]:
        raise NykraError("Manifest startup path does not match; refusing removal")
    if autostart.exists() and not status["autostart_registered"]:
        raise NykraError("Startup entry has changed; refusing to delete an unmanaged file")
    stop = request_stop(root)
    if not stop["stopped"]:
        raise NykraError("Background runtime is still running; refusing uninstall")
    assert_not_running(root)
    if autostart.exists():
        autostart.unlink()
    runtime = root / "runtime"
    if runtime.is_dir():
        shutil.rmtree(runtime)
    (root / "installation.json").unlink()
    return {"uninstalled": True, "history_preserved": True,
            "autostart_removed": True, "background_stopped": True}
